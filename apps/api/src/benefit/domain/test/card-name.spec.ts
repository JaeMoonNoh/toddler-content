import { describe, expect, it } from 'vitest';

import { toCardName } from '../card-name';

describe('toCardName', () => {
  it.each([
    ['(경기도 수원시) 출산지원금', '출산지원금'],
    ['(서울 중구) 난임부부 시술 약제비 지원', '난임부부 시술 약제비 지원'],
    ['[강남구] 산후조리비 지원', '산후조리비 지원'],
    ['수원시] 출산지원금', '출산지원금'],
    ['임신축하금 지원(고양시)', '임신축하금 지원'],
    ['경기도 산후조리비 지원', '산후조리비 지원'],
    ['서울특별시 서울형 키즈카페 운영', '서울형 키즈카페 운영'],
    ['서울시 임산부 교통비 지원', '임산부 교통비 지원'],
    ['서울시한의약난임치료지원', '한의약난임치료지원'],
  ])('지역 머리말·꼬리말을 뗀다: %s', (source, name) => {
    expect(toCardName(source)).toBe(name);
  });

  it.each([
    '수도요금 감면(다자녀)',
    '서울형 산후조리경비 지원',
    '서울 난자동결 시술비용 지원',
    '이주여성 건강관리 지원 (구)다문화가족 돌봄)',
  ])('지역이 아닌 말은 그대로 둔다: %s', (source) => {
    expect(toCardName(source)).toBe(source);
  });
});
